// A fast drop-in for makefun-site 1.0.0: run(input) returns, for one case's input,
// exactly the output tree makefun-site 1.0.0's build returns, byte for byte.
// Written from the README's rules and the reference's behaviour; the speed comes
// from doing the same work with less of it: one fused Markdown pass that escapes
// plain text in bulk instead of a character at a time, a front-matter scanner
// that never splits the body, cached slugs, a manual word count, and a template
// interpreter that reuses one frame per loop instead of one per element.

